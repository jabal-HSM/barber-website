export function at(lang, key, params = {}) {
    const template = adminTranslations[lang]?.[key] ?? adminTranslations.fr[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}
